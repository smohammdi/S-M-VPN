/// App language options. `system` follows the device language.
enum AppLanguage { system, english, persian }

/// Holds the active language, persists it with SharedPreferences,
/// and rebuilds the UI on change.
class LanguageProvider extends ChangeNotifier {
  LanguageProvider({String initialCode = 'system'})
      : _code = _normalize(initialCode);

  String _code;

  static String _normalize(String code) {
    if (code == 'en' || code == 'fa') return code;
    return 'system';
  }

  String get code => _code;

  AppLanguage get language => _code == 'en'
      ? AppLanguage.english
      : _code == 'fa'
          ? AppLanguage.persian
          : AppLanguage.system;

  /// Null means "follow the device language".
  Locale? get locale => _code == 'en'
      ? const Locale('en')
      : _code == 'fa'
          ? const Locale('fa')
          : null;

  Future<void> setLanguage(AppLanguage language) async {
    final code = language == AppLanguage.english
        ? 'en'
        : language == AppLanguage.persian
            ? 'fa'
            : 'system';
    if (code == _code) return;
    _code = code;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('app_language', code);
    notifyListeners();
  }

  static Future<String> loadCode() async {
    final prefs = await SharedPreferences.getInstance();
    return _normalize(prefs.getString('app_language') ?? 'system');
  }
}

